// The showcase shelf, in the order it reads: what is not on it nor real life is a control.
const SHOWCASE = new Set(SHOWCASE_ORDER);

export const shelfOf = (name: string): Shelf => {
  if (REAL.has(name)) return "real";
  return SHOWCASE.has(name) ? "showcase" : "control";
};

const rank = (one: Fixture): number => {
  const place = SHOWCASE_ORDER.indexOf(one.name);
  return place >= 0 ? place : Number.MAX_SAFE_INTEGER;
};

export const simpleFirst = (a: Fixture, b: Fixture): number =>
  rank(a) - rank(b) ||
  Number(!a.label.startsWith("Basic")) - Number(!b.label.startsWith("Basic")) ||
  a.source.length - b.source.length ||
  a.label.localeCompare(b.label);
