export const DEFAULT_CHARSET = "unicode";
export const CHARSETS: ReadonlyMap<string, CharSet> = new Map([
  [UNICODE.name, UNICODE],
  [COMPAT.name, COMPAT],
]);
export const CHARSET_NAMES: readonly string[] = [...CHARSETS.keys()];
export function charsetOf(name: string | undefined = DEFAULT_CHARSET): CharSet {
  const cs = CHARSETS.get(name);
  if (cs === undefined) throw new Error(`charset: ${name} is not a charset this draws with (${CHARSET_NAMES.join(", ")})`);
  return cs;
}

